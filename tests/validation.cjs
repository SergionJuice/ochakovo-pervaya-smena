const fs=require('node:fs');
const vm=require('node:vm');
const assert=require('node:assert/strict');
const source=fs.readFileSync('public/data.js','utf8');
const element={addEventListener(){},innerHTML:'',textContent:''};
const context={document:{querySelector:()=>element,addEventListener(){}},localStorage:{getItem:()=>null,setItem(){}},structuredClone,Date,setTimeout};
vm.createContext(context);
vm.runInContext(source+';this.validateForm=validate;',context);
const base={name:'Алексей Примеров',contact:'test@example.com',dob:'2004-06-15',job:'lab',readiness:'В течение месяца',education:'Тестовый университет'};
const now=new Date(2026,9,23,12);
const check=(changes)=>context.validateForm({...base,...changes},now);
assert.equal(Object.keys(check({})).length,0);
assert.equal(Object.keys(check({dob:'2008-10-23'})).length,0,'Exact 18th birthday is accepted');
assert.ok(check({dob:'2008-10-24'}).dob,'Under 18 by one day is rejected');
assert.ok(check({dob:'2027-01-01'}).dob,'Future birthday is rejected');
assert.ok(check({dob:'2004-02-30'}).dob,'Invalid calendar day is rejected');
assert.equal(Object.keys(check({dob:'2004-02-29'})).length,0,'Valid leap day accepted');
assert.ok(check({contact:'not-an-email'}).contact);
assert.ok(check({contact:'+7 123'}).contact);
assert.equal(Object.keys(check({contact:'+7 (999) 123-45-67'})).length,0);
assert.ok(check({name:'Алексей'}).name);
assert.ok(check({education:'  '}).education);
assert.ok(check({job:'unknown'}).job);
assert.ok(check({readiness:''}).readiness);
assert.equal(Object.keys(context.validateForm({},now)).length,6);
console.log('PASS: 14 form validation checks (required fields, age boundaries, dates, contact and options).');
